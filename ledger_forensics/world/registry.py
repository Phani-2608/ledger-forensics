@dataclass
class Ledger:
    """Transaction ledger for the closed world."""
    records: Dict[str, TransactionRecord] = field(default_factory=dict)

    def add(self, rec: TransactionRecord) -> None:
        self.records[rec.transaction_id] = rec

    def get(self, transaction_id: str) -> Optional[TransactionRecord]:
        return self.records.get(transaction_id)

    def __len__(self) -> int:
        return len(self.records)


def tax_rate_for(merchant_id: str) -> float:
    """Authoritative tax rate for a merchant, from the registry."""
    merchant = MERCHANTS[merchant_id]
    return JURISDICTIONS[merchant.jurisdiction].tax_rate


def auth_code(seed: str) -> str:
    return hashlib.sha1(seed.encode()).hexdigest()[:6].upper()
