"""Closed-world registry.

Every "fact" the semantic checks rely on is defined here and generated by this
system. We are not asserting anything about real merchants or real tax law.
That distinction is the whole reason the semantic channel is defensible: the
reference data is ground truth *inside the simulated world*, not knowledge
recalled from a model.

See docs/SCOPE.md for the external-validity limits this implies.
"""

from __future__ import annotations

import hashlib
from dataclasses import dataclass, field
from typing import Dict, List, Optional


@dataclass(frozen=True)
class Jurisdiction:
    code: str
    name: str
    tax_rate: float  # authoritative inside this world


@dataclass(frozen=True)
class Merchant:
    merchant_id: str
    name: str
    jurisdiction: str
    category: str
    template_id: str          # which layout template this merchant always uses
    address: str
    phone: str


@dataclass
class TransactionRecord:
    """The payment-network side of the story.

    A submitted document claims an amount. The ledger says what was actually
    charged. Disagreement is the single strongest semantic signal in the system
    and it is the one closest to real payments work.
    """
    transaction_id: str
    merchant_id: str
    amount: float
    date: str
    card_last4: str
    auth_code: str


